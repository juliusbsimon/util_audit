Each audited table has a trigger that runs after every insert, update and delete, once per row.

## What is recorded

- One **event** per changed row: when, who, the kind of change, the row's key, and the whole row before and after.
- One **column change** per changed column, with the old and new value. For an insert or a delete, every column that has a value.

