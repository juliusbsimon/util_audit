Moves old audit history out of the audit tables into files, preferably in Amazon S3, and brings it back when needed.

## How it works

Each file holds one table's events for one calendar month, as gzipped JSON lines. Every archive goes through these steps:

1. **Archive**: the file is built.
2. **Store**: the file is sent to its storage, then read back and compared, so a damaged upload is never counted as stored.
3. **Purge** (only if you turn it on): the month's events are deleted from the audit tables, after checking that they still match the file.
4. **Restore** (when needed): the month's events are loaded back. Loading twice does no harm.

## Storage and retention

| Storage | Where the files go |
|---|---|
| Database | Kept in the archive table itself |
| Amazon S3 via AWS4_S3_PKG | Your bucket, through the S3 package this schema already uses for documents |
| Object storage via DBMS_CLOUD | Needs a DBMS_CLOUD credential and a base URI |
| Custom procedure | Your own procedure and function, for any other system |

**Months to keep** says how many recent months stay in the audit tables; older complete months are archived. **Delete archived months** is off at first, so the first runs only make copies. Turn it on once you have restored one archive and checked it.

## Schedule

**Schedule** creates a database job that archives every night (it needs the CREATE JOB privilege). **Run Now** does the same work straight away. The last run's result shows here; a failed step says why in the file list.

## Archive files

One row per file, with its status: Created, Stored, Purged, Restored or Failed. You can store a file again after a failure, purge it, restore it, or download it.

A restored month is archived again by the next scheduled run. To keep it in the tables for a while, stop the schedule or raise **Months to keep**.
