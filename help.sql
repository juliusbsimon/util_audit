-- util_audit in-app help
--
-- One UTIL_AUDIT_DOC_ARTICLE row per topic, written in Markdown and rendered
-- with APEX_MARKDOWN.TO_HTML on the app's Documentation page (page 9).
-- PAGE_ID links an article to the screen it explains: Help in the top bar
-- opens page 9 with the current page number, and page 9 shows that article.
-- ADMIN_ONLY = Y hides an article from users who are not workspace
-- administrators or developers.
--
-- Installed by the Util Audit app's Supporting Objects. Safe to re-run: the
-- table is created only when missing. A missing article is added. An
-- article nobody has edited gets the new text; SEED_BODY keeps the text it
-- was shipped with, so an article edited in the app is never overwritten.
------------------------------------------------------------------------------

DECLARE
    PROCEDURE ddl(p_sql IN VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
    EXCEPTION
        WHEN OTHERS THEN
            -- ORA-00955: name already used, ORA-02260/02261: key already exists,
            -- ORA-01430: column already exists
            IF SQLCODE NOT IN (-955, -2260, -2261, -1430) THEN
                RAISE;
            END IF;
    END;
BEGIN
    ddl(q'[
create table UTIL_AUDIT_DOC_ARTICLE
(
    ID          NUMBER generated by default on null as identity
        constraint UTIL_AUDIT_DOC_ARTICLE_PK
            primary key,
    SLUG        VARCHAR2(100)  not null
        constraint UTIL_AUDIT_DOC_ARTICLE_SLUG_UK
            unique,
    TITLE       VARCHAR2(200)  not null,
    PAGE_ID     NUMBER,
    ADMIN_ONLY  VARCHAR2(1)    default 'N' not null
        constraint UTIL_AUDIT_DOC_ARTICLE_ADM_CK
            check (admin_only in ('Y', 'N')),
    SORT_ORDER  NUMBER         default 100 not null,
    BODY        CLOB,
    ACTIVE      VARCHAR2(1)    default 'Y' not null
        constraint UTIL_AUDIT_DOC_ARTICLE_ACT_CK
            check (active in ('Y', 'N')),
    CREATED     DATE           not null,
    CREATED_BY  VARCHAR2(255)  not null,
    UPDATED     DATE           not null,
    UPDATED_BY  VARCHAR2(255)  not null
)]');

    ddl(q'[create index UTIL_AUDIT_DOC_ARTICLE_PAGE_IX
    on UTIL_AUDIT_DOC_ARTICLE (PAGE_ID)]');

    -- The text the article was shipped with (added later)
    ddl(q'[alter table UTIL_AUDIT_DOC_ARTICLE add (SEED_BODY CLOB)]');
END;
/

create or replace trigger UTIL_AUDIT_DOC_ARTICLE_BIU
    before insert or update on UTIL_AUDIT_DOC_ARTICLE
    for each row
begin
    if inserting then
        :new.created    := sysdate;
        :new.created_by := nvl(sys_context('APEX$SESSION', 'APP_USER'), user);
    end if;
    :new.updated    := sysdate;
    :new.updated_by := nvl(sys_context('APEX$SESSION', 'APP_USER'), user);
    :new.slug       := lower(regexp_replace(trim(:new.slug), '[^A-Za-z0-9-]+', '-'));
end;
/

-- Seed articles. Blank lines inside a PL/SQL block are safe in SQL*Plus,
-- SQLcl and APEX script runs, so the Markdown keeps its paragraphs.
DECLARE
    PROCEDURE seed(
        p_slug       IN VARCHAR2,
        p_title      IN VARCHAR2,
        p_page_id    IN NUMBER,
        p_admin_only IN VARCHAR2,
        p_sort_order IN NUMBER,
        p_body       IN CLOB
    ) IS
    BEGIN
        -- Unedited: the body is still the shipped text. Rows from before
        -- SEED_BODY existed count as unedited if never updated after insert.
        UPDATE util_audit_doc_article a
           SET body = p_body, seed_body = p_body
         WHERE a.slug = p_slug
           AND (DBMS_LOB.COMPARE(a.body, a.seed_body) = 0
                OR (a.seed_body IS NULL AND a.updated <= a.created + 2 / 86400)
                OR DBMS_LOB.COMPARE(a.body, p_body) = 0)
           -- only when something changes, so a re-run touches nothing
           AND (NVL(DBMS_LOB.COMPARE(a.body, p_body), 1) <> 0
                OR NVL(DBMS_LOB.COMPARE(a.seed_body, p_body), 1) <> 0);

        INSERT INTO util_audit_doc_article (slug, title, page_id, admin_only, sort_order, body, seed_body)
        SELECT p_slug, p_title, p_page_id, p_admin_only, p_sort_order, p_body, p_body
        FROM dual
        WHERE NOT EXISTS (SELECT 1 FROM util_audit_doc_article WHERE slug = p_slug);
    END;
