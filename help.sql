## Supported column types

NUMBER, FLOAT, BINARY_FLOAT, BINARY_DOUBLE, VARCHAR2, CHAR, NVARCHAR2, NCHAR, DATE, TIMESTAMP (with or without time zone), INTERVAL, CLOB and RAW (stored as hex). Other types, such as BLOB, are skipped.

Numbers and dates are always written the same way, whatever the user's language settings: `1234.5` and `2026-02-03T00:00:00`.

## Keys

A table needs a primary key. A key of one column is stored as its value, for example `42`. A key of several columns is stored as `{"ORDER_ID":"100","LINE_NO":"1"}`.

## Transactions

Audit records are part of the same transaction as the change. If the change is rolled back, so is its record.

## Speed

Every audited change does extra work. Audit the tables that matter, and avoid staging tables, bulk loads and high-volume logging tables.
